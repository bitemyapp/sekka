//! The small, lossless migration from the original installer's flake.
//! Unknown customizations fail closed; hardware and user modules are never rewritten.
use rnix::ast::{self, HasEntry};
use rowan::ast::AstNode;

use crate::edit;

const EXTERNAL: &[&str] = &["nixpkgs", "determinate", "fh", "applications", "ai-apps", "omp"];
const LEGACY: &[&str] = &["calamares", "tatami", "yukimi"];
const UNSUPPORTED: &str = "This flake needs a manual migration to Sekka; no files were changed";
const LEGACY_HEADER: &str = "# Generated by the unofficial graphical installer with Determinate Nix.\n\
# flake.lock records the same tested revisions as the installation media.\n\
# Update everything with `nix flake update`, only the installer's desktop,\n\
# tuning and application modules with `nix flake update calamares`, only the\n\
# Tatami desktop with `nix flake update tatami`, or only the Yukimi app with\n\
# `nix flake update yukimi`; then run `nixos-rebuild boot --flake /etc/nixos`.\n\
# Yukimi does all of this from its Updates page.\n";

/// Already on Sekka, or a supported predecessor installation.
pub fn supported(text: &str) -> bool {
    prepare(text).is_ok()
}

/// What Sekka systems follow: the branch the nightly workflow moves only
/// after its checks have passed and Sekka's packages are in its binary cache.
/// `main` moves first, so a system following it could compile them itself.
pub const NIGHTLY: &str = "github:bitemyapp/sekka/nightly";

/// Return the flake to update. A system following `main` (or the default
/// branch) follows `nightly` instead; other Sekka branches and pins stay as
/// chosen.
pub fn prepare(text: &str) -> Result<String, String> {
    if let Some(url) = edit::string_value(text, &["inputs", "sekka", "url"]).map_err(|e| e.to_string())? {
        if !official(&url, "sekka") {
            return Err(UNSUPPORTED.into());
        }
        if url == "github:bitemyapp/sekka" || url == "github:bitemyapp/sekka/main" {
            return edit::set_string_value(text, &["inputs", "sekka", "url"], NIGHTLY).map_err(|e| e.to_string());
        }
        return Ok(text.to_owned());
    }
    migrate(text).ok_or_else(|| UNSUPPORTED.into())
}

fn official(url: &str, repo: &str) -> bool {
    let base = format!("github:bitemyapp/{repo}");
    url == base || url.strip_prefix(&base).is_some_and(|s| s.starts_with('/') || s.starts_with('?'))
}

fn migrate(text: &str) -> Option<String> {
    let parsed = ast::Root::parse(text);
    if !parsed.errors().is_empty() {
        return None;
    }
    let ast::Expr::AttrSet(set) = parsed.tree().expr()? else { return None };
    // Only migrate the installer's explicit, flat input declarations. Refuse
    // nested/computed declarations instead of risking unrelated configuration.
    let mut edits = Vec::new();
    let mut seen = std::collections::BTreeSet::new();
    for entry in set.attrpath_values() {
        let path = entry.attrpath()?.to_string();
        let parts: Vec<_> = path.split('.').map(str::trim).collect();
        if parts.first() != Some(&"inputs") {
            continue;
        }
        let name = *parts.get(1)?;
        if !LEGACY.contains(&name) {
            continue;
        }
        let value = edit::string_value(text, &parts).ok()??;
        match parts.as_slice() {
            ["inputs", _, "url"] if official(&value, name) => {
                seen.insert(name.to_owned());
            }
            ["inputs", _, "inputs", "nixpkgs", "follows"] if value == "nixpkgs" => {}
            ["inputs", "calamares", "inputs", dep, "follows"]
                if ["tatami", "yukimi"].contains(dep) && value == *dep => {}
            _ => return None,
        }
        edits.push((entry.syntax().text_range(), String::new()));
    }
    if !LEGACY.iter().all(|name| seen.contains(*name)) {
        return None;
    }
    for name in EXTERNAL {
        edit::string_value(text, &["inputs", name, "url"]).ok()??;
    }
    let outputs = set.attrpath_values().find(|e| e.attrpath().is_some_and(|p| p.to_string() == "outputs"))?;
    let ast::Expr::Lambda(lambda) = outputs.value()? else { return None };
    let mut parameter = false;
    let mut module = false;
    // Only the parameter and its module reference may use the old name.
    // Comments and strings are deliberately not substituted.
    for ident in parsed.tree().syntax().descendants().filter_map(ast::Ident::cast) {
        let name = ident.to_string();
        if !LEGACY.contains(&name.as_str()) {
            continue;
        }
        let range = ident.syntax().text_range();
        if edits.iter().any(|(r, _)| r.contains_range(range)) {
            continue;
        }
        if name != "calamares" || !lambda.syntax().text_range().contains_range(range) {
            return None;
        }
        let parent = ident.syntax().parent()?;
        if parent.kind() == rnix::SyntaxKind::NODE_PAT_ENTRY && !parameter {
            parameter = true;
        } else if ast::Select::cast(parent).is_some_and(|s| {
            s.expr().is_some_and(|e| e.syntax() == ident.syntax())
                && s.attrpath().is_some_and(|p| p.to_string() == "nixosModules.default")
        }) && !module
        {
            module = true;
        } else {
            return None;
        }
        edits.push((range, "sekka".into()));
    }
    if !parameter || !module {
        return None;
    }
    let mut inputs = format!("inputs.sekka.url = \"{NIGHTLY}\";");
    for name in EXTERNAL {
        inputs.push_str(&format!("\n  inputs.sekka.inputs.{name}.follows = \"{name}\";"));
    }
    edits.first_mut()?.1 = inputs;
    edits.sort_by_key(|(range, _)| std::cmp::Reverse(range.start()));
    let mut result = text.to_owned();
    for (range, replacement) in edits {
        result.replace_range(usize::from(range.start())..usize::from(range.end()), &replacement);
    }
    if !ast::Root::parse(&result).errors().is_empty() {
        return None;
    }
    if let Some(body) = result.strip_prefix(LEGACY_HEADER) {
        result = format!(
            "# Migrated to Sekka. Update through Yukimi or `sekka-update`.\n# Independent package pins remain in flake.lock.\n{body}"
        );
    }
    Some(result)
}

#[cfg(test)]
mod tests {
    use super::*;
    const OLD: &str = include_str!("../tests/legacy-flake.nix");

    #[test]
    fn migrates_installer_without_changing_custom_settings() {
        let text = OLD.replace("./configuration.nix", "./configuration.nix ./custom.nix");
        let new = prepare(&text).unwrap();
        assert!(new.contains("sekka.nixosModules.default"));
        assert!(new.contains("omp, sekka, ..."));
        assert!(new.contains("./configuration.nix ./custom.nix"));
        assert!(!new.contains("inputs.tatami"));
        assert!(!new.contains("inputs.calamares"));
        for name in EXTERNAL {
            assert_eq!(
                edit::string_value(&new, &["inputs", name, "url"]).unwrap(),
                edit::string_value(&text, &["inputs", name, "url"]).unwrap()
            );
            assert_eq!(
                edit::string_value(&new, &["inputs", "sekka", "inputs", name, "follows"]).unwrap().as_deref(),
                Some(*name)
            );
        }
        assert_eq!(prepare(&new).unwrap(), new);
    }

    #[test]
    fn leaves_existing_sekka_branch_alone() {
        let new = prepare(OLD).unwrap().replace("sekka/nightly", "sekka/topic");
        assert!(new.contains("github:bitemyapp/sekka/topic"));
        assert_eq!(prepare(&new).unwrap(), new);
    }

    #[test]
    fn follows_nightly_instead_of_main() {
        let nightly = prepare(OLD).unwrap();
        assert_eq!(edit::string_value(&nightly, &["inputs", "sekka", "url"]).unwrap().as_deref(), Some(NIGHTLY));
        for main in ["github:bitemyapp/sekka/main", "github:bitemyapp/sekka"] {
            let text = nightly.replace(NIGHTLY, main);
            assert_eq!(prepare(&text).unwrap(), nightly, "{main}");
        }
    }

    #[test]
    fn refuses_unrecognized_or_ambiguous_sources() {
        for old in [
            OLD.replace("bitemyapp/calamares", "someone/calamares"),
            OLD.replace("./configuration.nix", "tatami.nixosModules.default ./configuration.nix"),
            OLD.replace("inputs.tatami.url", "inputs.other.url"),
            OLD.replace("outputs =", "inputs.calamares.inputs.extra.follows = \"x\"; outputs ="),
            "{ inputs.sekka.url = \"github:bitemyapp/sekka-evil\"; }".into(),
            "{ broken".into(),
        ] {
            assert!(prepare(&old).is_err(), "{old}");
        }
    }
}
