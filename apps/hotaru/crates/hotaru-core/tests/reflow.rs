use hotaru_core::{Color, Rgb, Snapshot, Terminal};
use serde_json::{Value, json};

fn color(value: Color) -> Value {
    match value {
        Color::Default => json!({"default":true}),
        Color::Indexed(index) => json!({"index":index}),
        Color::Rgb(Rgb(r, g, b)) => json!({"rgb":[r,g,b]}),
    }
}

fn compact_snapshot(snapshot: &Snapshot, rows: usize, history: usize, responses: Vec<u8>) -> Value {
    let lines: Vec<_> = snapshot
        .lines
        .iter()
        .map(|row| {
            let cells: Vec<_> = row
                .cells()
                .iter()
                .enumerate()
                .map(|(col, &cell)| {
                    let style = row.style(cell);
                    let mut fields = vec![
                        json!(
                            row.grapheme(col)
                                .map(str::to_owned)
                                .unwrap_or_else(|| cell.character().to_string())
                        ),
                        json!(cell.width()),
                    ];
                    if style != hotaru_core::Style::default() || cell.is_protected() {
                        fields.extend([
                            color(style.foreground),
                            color(style.background),
                            color(style.underline_color),
                            json!(style.attrs),
                            json!(cell.is_protected()),
                        ]);
                    }
                    Value::Array(fields)
                })
                .collect();
            json!([row.wrapped(), cells])
        })
        .collect();
    json!({"cols":snapshot.cols,"rows":rows,"history":history,
        "cursor":[snapshot.cursor.col,snapshot.cursor.row],"responses":responses,"lines":lines})
}

#[test]
fn resize_matches_actual_ghostty_oracle_across_input_chunks() {
    // Expectations are generated by the pinned libghostty-vt, never by Hotaru.
    let fixture: Value =
        serde_json::from_str(include_str!("../../../upstream/reflow-fixtures.json")).unwrap();
    assert_eq!(
        fixture["ghostty_commit"],
        "6ba144158577d033ccb6ed4b574e4013957c9161"
    );
    for case in fixture["cases"].as_array().unwrap() {
        for chunk in [1, 7, usize::MAX] {
            let mut terminal = Terminal::new(
                case["cols"].as_u64().unwrap() as usize,
                case["rows"].as_u64().unwrap() as usize,
                case["history"].as_u64().unwrap_or(10_000) as usize,
            );
            for (step, (op, want)) in case["ops"]
                .as_array()
                .unwrap()
                .iter()
                .zip(case["expected"].as_array().unwrap())
                .enumerate()
            {
                if let Some(text) = op["write"].as_str() {
                    for part in text.as_bytes().chunks(chunk) {
                        terminal.feed(part);
                    }
                }
                if let Some(size) = op["resize"].as_array() {
                    terminal.resize(
                        size[0].as_u64().unwrap() as usize,
                        size[1].as_u64().unwrap() as usize,
                    );
                }
                let actual = compact_snapshot(
                    &terminal.snapshot_all(),
                    terminal.snapshot().rows,
                    terminal.scrollback_len(),
                    terminal.take_responses(),
                );
                assert_eq!(
                    &actual, want,
                    "case {} step {step} chunk {chunk}",
                    case["name"]
                );
            }
        }
    }
}

#[test]
fn snapshots_keep_cells_styles_and_graphemes_across_reflow_and_teardown() {
    let mut terminal = Terminal::new(8, 4, 100);
    terminal.feed("\x1b[31;44mab雪\u{301}cdefghijkl\x1b[0m".as_bytes());
    let snapshot = terminal.snapshot_all();
    let expected = compact_snapshot(&snapshot, 4, 0, Vec::new());
    for (cols, rows) in [(3, 2), (1, 1), (18, 8), (4, 5), (80, 24)] {
        terminal.resize(cols, rows);
        terminal.feed(b"\x1b[2J\x1b[Hnew content");
    }
    drop(terminal);
    assert_eq!(compact_snapshot(&snapshot, 4, 0, Vec::new()), expected);
    assert_eq!(std::mem::size_of::<hotaru_core::Cell>(), 8);
}

#[test]
fn narrow_reflow_keeps_history_bounded_and_wide_pairs_valid() {
    let mut terminal = Terminal::new(120, 24, 37);
    for _ in 0..1000 {
        terminal.feed("prefix 雪花 e\u{301} tail\r\n".as_bytes());
    }
    for (cols, rows) in [(1, 1), (3, 2), (240, 30), (2, 4), (80, 24)] {
        terminal.resize(cols, rows);
        assert!(terminal.scrollback_len() <= 37);
        let snapshot = terminal.snapshot_all();
        assert_eq!(snapshot.lines.len(), rows + terminal.scrollback_len());
        for row in &snapshot.lines {
            assert_eq!(row.cells().len(), cols);
            for (col, cell) in row.cells().iter().enumerate() {
                match cell.width() {
                    0 => assert!(col > 0 && row.cells()[col - 1].width() == 2),
                    2 => assert!(col + 1 < cols && row.cells()[col + 1].width() == 0),
                    1 => {}
                    _ => panic!("invalid cell width"),
                }
            }
        }
    }
}

#[test]
fn copying_reflowed_wide_text_omits_layout_spacers() {
    let mut terminal = Terminal::new(8, 4, 100);
    terminal.feed("abcdefg雪xyz".as_bytes());
    for (cols, rows) in [(8, 4), (3, 4), (13, 3), (2, 4)] {
        terminal.resize(cols, rows);
        assert_eq!(
            terminal.snapshot_all().plain_text().trim_end(),
            "abcdefg雪xyz"
        );
    }
}
