#!/usr/bin/env python3
"""Translate the pinned Ghostty-generated property table into Rust data.

Run after building the reference library, passing its generated props.zig and
the pinned uucode checkout. No Zig source/compiler is required at runtime.
The generator rejects an unexpected layout instead of guessing enum values.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--props", required=True, type=Path)
    parser.add_argument("--uucode", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--manifest", required=True, type=Path)
    args = parser.parse_args()
    source = args.props.read_text()
    types = (args.uucode / "src/types.zig").read_text()
    enum = re.search(r"pub const GraphemeBreakNoControl = enum\(u5\) \{(.*?)\n\};", types, re.S).group(1)
    enum = re.sub(r"//[^\n]*", "", enum)
    names = [name.strip() for name in enum.split(",") if name.strip()]
    expected = "other prepend regional_indicator spacing_mark l v t lv lvt zwj zwnj extended_pictographic emoji_modifier_base emoji_modifier indic_conjunct_break_extend indic_conjunct_break_linker_extend indic_conjunct_break_linker_other indic_conjunct_break_consonant".split()
    if names != expected:
        raise ValueError("unexpected pinned grapheme property enum")
    stages = []
    for number in (1, 2):
        match = re.search(rf"pub const stage{number}: \[(\d+)\]u16 = \.\{{(.*?)\}};", source, re.S)
        values = [int(value) for value in match.group(2).split(",") if value.strip()]
        assert len(values) == int(match.group(1))
        stages.append(values)
    records = re.findall(r"\.width=\s*(\d+),\s*\.width_zero_in_grapheme=\s*(true|false),\s*\.grapheme_break=\s*\.(\w+),\s*\.emoji_vs_base=\s*(true|false),", source)
    assert records
    props = [int(width) | ((zero == "true") << 2) | (names.index(name) << 3) | ((vs == "true") << 8) for width, zero, name, vs in records]
    # Rust char cannot exceed U+10FFFF; upstream's u21 table has extra pages.
    stages[0] = stages[0][:0x110000 // 256]
    assert len(stages[0]) == 4352
    assert max(stages[0]) + 255 < len(stages[1])
    assert max(stages[1]) < len(props)
    output = ["// Generated by tools/unicode-tables.py; do not edit.\n",
              "// Ghostty 6ba144158577d033ccb6ed4b574e4013957c9161; uucode ea62149739404a73c202b48a33bf6dd2af4bd9b0.\n",
              "// Unicode 18.0.0 data. See upstream/LICENSE.ghostty, LICENSE.uucode, LICENSE.unicode.\n"]
    for name, values in zip(("STAGE1", "STAGE2", "PROPERTIES"), (*stages, props)):
        output.append("#[rustfmt::skip]\n")
        output.append(f"pub(super) static {name}: [u16; {len(values)}] = [\n")
        for offset in range(0, len(values), 24):
            output.append("    " + ", ".join(map(str, values[offset:offset + 24])) + ",\n")
        output.append("];\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(output))
    manifest = {
        "ghostty_revision": "6ba144158577d033ccb6ed4b574e4013957c9161",
        "uucode_revision": "ea62149739404a73c202b48a33bf6dd2af4bd9b0",
        "unicode_version": "18.0.0",
        "generated_props_sha256": sha(args.props),
        "uucode_types_sha256": sha(args.uucode / "src/types.zig"),
        "uucode_grapheme_sha256": sha(args.uucode / "src/grapheme.zig"),
        "generator_sha256": sha(__file__),
        "rust_table_sha256": sha(args.output),
        "entries": dict(zip(("stage1", "stage2", "properties"), map(len, (*stages, props)))),
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest))


if __name__ == "__main__":
    main()
