//! User accounts, through AccountsService: the people who can log in, with
//! their real names, pictures, account types and last logins; changing
//! names, pictures and account types; setting passwords; creating and
//! deleting accounts.
//!
//! Passwords are hashed here with SHA-512 crypt (`$6$rounds=…$salt$hash`,
//! which glibc and libxcrypt verify) with a random salt, and only the hash
//! goes over the bus (`User.SetPassword` takes a crypted password).
//!
//! Changing another account, or one's own type, asks polkit (as
//! administrator); one's own name, picture and password need only one's own
//! authentication. Needs `services.accounts-daemon.enable` (on by default
//! with most desktop modules). On NixOS creating, deleting and changing
//! users works with `users.mutableUsers = true` (the default); with
//! `mutableUsers = false` the next rebuild resets `/etc/passwd`, so the
//! snapshot reports it ([`UsersState::users_managed`]).

use crate::bus::{self, Bus, Event, Objects, Opts, Props, PropsExt, signals_from};
use crate::error::{Error, Result};
use crate::service::{Model, Stop, Task, Wake, service_handle};
use std::sync::Arc;
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use zbus::zvariant::OwnedObjectPath;

const ACCOUNTS: &str = "org.freedesktop.Accounts";
const ACCOUNTS_PATH: &str = "/org/freedesktop/Accounts";
const IFACE_USER: &str = "org.freedesktop.Accounts.User";
const IFACE_AIZOME: &str = "org.aizome.DisplayScales";

/// A person's public display scales for the login screen. AccountsService
/// persists this even when their home is unavailable before login.
pub fn display_scales(bus: &Bus, uid: u32) -> Result<String> {
    let path: OwnedObjectPath = bus.call(ACCOUNTS, ACCOUNTS_PATH, ACCOUNTS, "FindUserById", &(i64::from(uid),))?;
    bus.get(ACCOUNTS, path.as_str(), IFACE_AIZOME, "Scales")
}

/// Publish only our own display scales, without prompting for authentication.
/// The installed AccountsService extension permits changing one's own data;
/// changing another person's still requires administrator authorization.
pub fn publish_display_scales(bus: &Bus, scales: &str) -> Result<()> {
    let uid = unsafe { libc::getuid() };
    let path: OwnedObjectPath = bus.call(ACCOUNTS, ACCOUNTS_PATH, ACCOUNTS, "FindUserById", &(i64::from(uid),))?;
    bus.call(
        ACCOUNTS,
        path.as_str(),
        "org.freedesktop.DBus.Properties",
        "Set",
        &(IFACE_AIZOME, "Scales", zbus::zvariant::Value::from(scales)),
    )
}

/// The rounds of SHA-512 crypt: slow enough to resist guessing, fast enough
/// (tens of milliseconds) at login.
const ROUNDS: usize = 100_000;

/// The accounts.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct UsersState {
    pub available: bool,
    /// People's accounts (not system accounts), by name.
    pub users: Vec<User>,
    /// The uid of the account running this process.
    pub current_uid: u64,
    /// `/etc/passwd` is generated by the system configuration
    /// (`users.mutableUsers = false`): changes don't last.
    pub users_managed: bool,
}

impl UsersState {
    pub fn current(&self) -> Option<&User> {
        self.users.iter().find(|u| u.uid == self.current_uid)
    }

    pub fn user(&self, name: &str) -> Option<&User> {
        self.users.iter().find(|u| u.name == name)
    }

    pub fn administrators(&self) -> impl Iterator<Item = &User> {
        self.users.iter().filter(|u| u.account_type == AccountType::Administrator)
    }
}

/// An account.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct User {
    pub path: String,
    pub uid: u64,
    /// The login name.
    pub name: String,
    /// The name to show ("Chris Allen").
    pub real_name: String,
    /// The picture's file, if it exists.
    pub icon_file: Option<String>,
    pub account_type: AccountType,
    pub home: String,
    pub shell: String,
    pub email: String,
    pub language: String,
    pub automatic_login: bool,
    pub locked: bool,
    pub password_mode: PasswordMode,
    /// When they last logged in.
    pub last_login: Option<SystemTime>,
    pub login_count: u64,
    pub system_account: bool,
    pub local_account: bool,
}

impl User {
    /// The name to show: the real name, else the login name.
    pub fn display_name(&self) -> &str {
        if self.real_name.trim().is_empty() { &self.name } else { &self.real_name }
    }

    /// Initials for a picture-less avatar ("CA").
    pub fn initials(&self) -> String {
        self.display_name()
            .split_whitespace()
            .filter_map(|word| word.chars().next())
            .take(2)
            .flat_map(char::to_uppercase)
            .collect()
    }
}

/// Standard or administrator (in `wheel`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum AccountType {
    #[default]
    Standard,
    Administrator,
}

impl AccountType {
    fn from_i64(n: i64) -> AccountType {
        if n == 1 { AccountType::Administrator } else { AccountType::Standard }
    }

    fn as_i32(self) -> i32 {
        match self {
            AccountType::Standard => 0,
            AccountType::Administrator => 1,
        }
    }
}

/// How the account's password works.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum PasswordMode {
    #[default]
    Regular,
    /// Choose one at the next login.
    SetAtLogin,
    /// No password.
    None,
}

impl PasswordMode {
    fn from_i64(n: i64) -> PasswordMode {
        match n {
            1 => PasswordMode::SetAtLogin,
            2 => PasswordMode::None,
            _ => PasswordMode::Regular,
        }
    }
}

pub(crate) fn user(path: &str, p: &Props) -> User {
    let icon = p.str("IconFile");
    User {
        path: path.to_owned(),
        uid: p.u64("Uid"),
        name: p.str("UserName"),
        real_name: p.str("RealName"),
        icon_file: Some(icon).filter(|f| !f.is_empty() && std::path::Path::new(f).is_file()),
        account_type: AccountType::from_i64(p.i64("AccountType")),
        home: p.str("HomeDirectory"),
        shell: p.str("Shell"),
        email: p.str("Email"),
        language: p.str("Language"),
        automatic_login: p.bool("AutomaticLogin"),
        locked: p.bool("Locked"),
        password_mode: PasswordMode::from_i64(p.i64("PasswordMode")),
        last_login: u64::try_from(p.i64("LoginTime"))
            .ok()
            .filter(|&t| t > 0)
            .map(|t| UNIX_EPOCH + Duration::from_secs(t)),
        login_count: p.u64("LoginFrequency"),
        system_account: p.bool("SystemAccount"),
        local_account: p.opt_bool("LocalAccount").unwrap_or(true),
    }
}

fn build(objects: &Objects, managed: bool) -> UsersState {
    let mut users: Vec<User> = objects
        .with(IFACE_USER)
        .map(|(path, p)| user(path, p))
        .filter(|u| !u.system_account && !u.name.is_empty())
        .collect();
    users.sort_by(|a, b| a.name.cmp(&b.name));
    UsersState {
        available: true,
        users,
        // SAFETY: getuid has no failure mode.
        current_uid: u64::from(unsafe { libc::getuid() }),
        users_managed: managed,
    }
}

/// Whether `/etc/passwd` comes from the Nix store (immutable users).
fn passwd_managed() -> bool {
    std::fs::read_link("/etc/passwd").is_ok_and(|t| t.starts_with("/etc/static") || t.starts_with("/nix/store"))
}

/// Whether a login name is acceptable: lowercase letters, digits, `_` and
/// `-`, starting with a letter or `_`, at most 32 characters.
pub fn valid_user_name(name: &str) -> bool {
    let mut chars = name.chars();
    matches!(chars.next(), Some(c) if c.is_ascii_lowercase() || c == '_')
        && name.len() <= 32
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '-')
}

/// Hash a password with SHA-512 crypt and a random salt.
pub fn crypt_password(password: &str) -> Result<String> {
    const ALPHABET: &[u8] = b"./0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
    let mut random = [0u8; 16];
    // SAFETY: getrandom writes at most `random.len()` bytes into it.
    let n = unsafe { libc::getrandom(random.as_mut_ptr().cast(), random.len(), 0) };
    if n != random.len() as isize {
        return Err(Error::Failed("no randomness for the salt".into()));
    }
    let salt: String = random.iter().map(|b| ALPHABET[usize::from(*b) % ALPHABET.len()] as char).collect();
    let params = sha_crypt::Sha512Params::new(ROUNDS).map_err(|e| Error::Failed(format!("{e:?}")))?;
    let hash = sha_crypt::sha512_crypt_b64(password.as_bytes(), salt.as_bytes(), &params)
        .map_err(|e| Error::Failed(format!("{e:?}")))?;
    Ok(format!("$6$rounds={ROUNDS}${salt}${hash}"))
}

/// Proof that the UI asked before deleting an account: made from the
/// account itself, so a stale uid can't delete someone else.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct DeleteUser {
    uid: u64,
    name: String,
    remove_files: bool,
}

impl DeleteUser {
    /// Delete `user`, and their home directory too when `remove_files`.
    pub fn confirm(user: &User, remove_files: bool) -> DeleteUser {
        DeleteUser { uid: user.uid, name: user.name.clone(), remove_files }
    }
}

/// AccountsService.
pub struct Users {
    bus: Option<Bus>,
    model: Arc<Model<UsersState>>,
    stop: Stop,
}

service_handle!(Users, UsersState);

impl Users {
    pub fn new(wake: Wake) -> Users {
        Users::with_bus(Bus::system().ok(), wake)
    }

    pub fn with_bus(bus: Option<Bus>, wake: Wake) -> Users {
        let model = Arc::new(Model::new(UsersState::default(), wake));
        let stop = Stop::default();
        if let Some(bus) = bus.clone() {
            let follower = model.clone();
            let managed = passwd_managed();
            let mut objects = Objects::default();
            let mut present = false;
            let mut dirty = false;
            let load_user = |bus: &Bus, objects: &mut Objects, path: &str| {
                if let Ok(props) = bus.get_all(ACCOUNTS, path, IFACE_USER) {
                    objects.map.entry(path.to_owned()).or_default().insert(IFACE_USER.into(), props);
                }
            };
            bus::follow(bus.clone(), ACCOUNTS, vec![signals_from(ACCOUNTS)], true, stop.clone(), move |bus, event| {
                match event {
                    Event::Appeared => {
                        present = true;
                        objects = Objects::default();
                        let paths: Vec<OwnedObjectPath> =
                            bus.call(ACCOUNTS, ACCOUNTS_PATH, ACCOUNTS, "ListCachedUsers", &()).unwrap_or_default();
                        for path in paths {
                            load_user(bus, &mut objects, path.as_str());
                        }
                        dirty = true;
                    }
                    Event::Vanished => {
                        present = false;
                        follower.set_if_changed(UsersState::default());
                    }
                    Event::Signal(msg) => {
                        let (iface, member) = bus::member(&msg);
                        match (iface.as_str(), member.as_str()) {
                            (ACCOUNTS, "UserAdded") => {
                                if let Ok(path) = msg.body().deserialize::<OwnedObjectPath>() {
                                    load_user(bus, &mut objects, path.as_str());
                                    dirty = true;
                                }
                            }
                            (ACCOUNTS, "UserDeleted") => {
                                if let Ok(path) = msg.body().deserialize::<OwnedObjectPath>() {
                                    objects.map.remove(path.as_str());
                                    dirty = true;
                                }
                            }
                            (IFACE_USER, "Changed") => {
                                load_user(bus, &mut objects, &bus::path(&msg));
                                dirty = true;
                            }
                            _ => {
                                let applied = objects.apply(&msg);
                                dirty |= applied.changed;
                            }
                        }
                    }
                    Event::Idle => {
                        if present && dirty {
                            follower.set_if_changed(build(&objects, managed));
                            dirty = false;
                        }
                    }
                }
            });
        }
        Users { bus, model, stop }
    }

    pub fn available(&self) -> bool {
        self.model.get().available
    }

    fn user_call<B>(&self, user: &User, method: &'static str, args: B) -> Task<()>
    where
        B: serde::Serialize + zbus::zvariant::DynamicType + Send + 'static,
    {
        let path = user.path.clone();
        bus::spawn(&self.bus, "AccountsService", self.model.wake(), move |bus| {
            bus.call_with(Opts::ACTION, ACCOUNTS, &path, IFACE_USER, method, &args)
        })
    }

    pub fn set_real_name(&self, user: &User, name: &str) -> Task<()> {
        if name.contains('\n') || name.contains(':') {
            return Task::ready(Err(Error::InvalidArgument("A name can't contain ':' or a line break".into())));
        }
        self.user_call(user, "SetRealName", (name.to_owned(),))
    }

    /// Set the account's picture: AccountsService copies the file.
    pub fn set_icon(&self, user: &User, file: &std::path::Path) -> Task<()> {
        if !file.is_file() {
            return Task::ready(Err(Error::NotFound(file.display().to_string())));
        }
        self.user_call(user, "SetIconFile", (file.to_string_lossy().into_owned(),))
    }

    /// Standard or administrator.
    pub fn set_account_type(&self, user: &User, account_type: AccountType) -> Task<()> {
        self.user_call(user, "SetAccountType", (account_type.as_i32(),))
    }

    pub fn set_automatic_login(&self, user: &User, on: bool) -> Task<()> {
        self.user_call(user, "SetAutomaticLogin", (on,))
    }

    pub fn set_locked(&self, user: &User, locked: bool) -> Task<()> {
        self.user_call(user, "SetLocked", (locked,))
    }

    /// Set the password (hashed here; only the hash is sent), with an
    /// optional hint.
    pub fn set_password(&self, user: &User, password: &str, hint: &str) -> Task<()> {
        if password.is_empty() {
            return Task::ready(Err(Error::InvalidArgument("The password is empty".into())));
        }
        let hashed = match crypt_password(password) {
            Ok(hashed) => hashed,
            Err(error) => return Task::ready(Err(error)),
        };
        self.user_call(user, "SetPassword", (hashed, hint.to_owned()))
    }

    /// Ask for a new password at the next login.
    pub fn require_password_change(&self, user: &User) -> Task<()> {
        self.user_call(user, "SetPasswordMode", (1i32,))
    }

    /// Create an account; the result is it, once AccountsService has it.
    pub fn create_user(&self, name: &str, real_name: &str, account_type: AccountType) -> Task<String> {
        if !valid_user_name(name) {
            return Task::ready(Err(Error::InvalidArgument(format!(
                "A user name is lowercase letters, digits, '_' and '-', starting with a letter: {name}"
            ))));
        }
        if self.model.get().user(name).is_some() {
            return Task::ready(Err(Error::InvalidArgument(format!("{name} already exists"))));
        }
        let args = (name.to_owned(), real_name.to_owned(), account_type.as_i32());
        bus::spawn(&self.bus, "AccountsService", self.model.wake(), move |bus| {
            let path: OwnedObjectPath =
                bus.call_with(Opts::ACTION, ACCOUNTS, ACCOUNTS_PATH, ACCOUNTS, "CreateUser", &args)?;
            Ok(path.to_string())
        })
    }

    /// Delete an account, as confirmed.
    pub fn delete_user(&self, confirmation: DeleteUser) -> Task<()> {
        let state = self.model.get();
        let Some(user) = state.users.iter().find(|u| u.uid == confirmation.uid && u.name == confirmation.name) else {
            return Task::ready(Err(Error::NotFound(confirmation.name)));
        };
        if user.uid == state.current_uid {
            return Task::ready(Err(Error::InvalidArgument("You can't delete your own account".into())));
        }
        let args = (i64::try_from(confirmation.uid).unwrap_or(-1), confirmation.remove_files);
        bus::spawn(&self.bus, "AccountsService", self.model.wake(), move |bus| {
            bus.call_with(Opts::ACTION, ACCOUNTS, ACCOUNTS_PATH, ACCOUNTS, "DeleteUser", &args)
        })
    }
}

impl Drop for Users {
    fn drop(&mut self) {
        self.stop.stop();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Check a password against `$6$rounds=N$salt$hash`, as crypt(3) does.
    pub(crate) fn verify(password: &str, hashed: &str) -> bool {
        let parts: Vec<&str> = hashed.split('$').collect();
        let [_, "6", rounds, salt, hash] = parts.as_slice() else { return false };
        let Some(rounds) = rounds.strip_prefix("rounds=").and_then(|r| r.parse().ok()) else { return false };
        let params = sha_crypt::Sha512Params::new(rounds).unwrap();
        sha_crypt::sha512_crypt_b64(password.as_bytes(), salt.as_bytes(), &params).is_ok_and(|h| h == *hash)
    }

    #[test]
    fn passwords_hash_as_glibc_expects() {
        let hashed = crypt_password("correct horse").unwrap();
        assert!(hashed.starts_with("$6$rounds=100000$"));
        assert!(verify("correct horse", &hashed));
        assert!(!verify("wrong", &hashed));
        // A known vector from the SHA-crypt paper.
        assert!(verify(
            "Hello world!",
            "$6$rounds=10000$saltstringsaltst$OW1/O6BYHV6BcXZu8QVeXbDWra3Oeqh0sbHbbMCVNSnCM/UrjmM0Dp8vOuZeHBy/YTBmSK6H9qs/y3RnOaw5v."
        ));
        assert_ne!(hashed, crypt_password("correct horse").unwrap(), "salted");
    }

    #[test]
    fn user_names() {
        assert!(valid_user_name("callen"));
        assert!(valid_user_name("_build-1"));
        assert!(!valid_user_name("Chris"));
        assert!(!valid_user_name("1abc"));
        assert!(!valid_user_name("a b"));
        assert!(!valid_user_name(""));
        assert!(!valid_user_name(&"a".repeat(33)));
    }

    #[test]
    fn initials_and_names() {
        let user = User { name: "callen".into(), real_name: "Chris Allen".into(), ..Default::default() };
        assert_eq!(user.initials(), "CA");
        let bare = User { name: "guest".into(), ..Default::default() };
        assert_eq!((bare.display_name(), bare.initials().as_str()), ("guest", "G"));
    }
}
