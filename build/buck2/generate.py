#!/usr/bin/env python3
"""Resolve Cargo units into Buck rules without maintaining a second dependency graph.

Requires the root-lock Nix environment and its offline, per-crate vendor paths.
Cargo's unit graph, rather than metadata's package-level feature union, owns
resolver 3 host/target features, build scripts, profiles and dependency renames.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tomllib

GENERATED = "# Generated by build/buck2/generate.py from Cargo unit graphs; do not edit.\n"
EXCLUDED = ["BUCK", "BUCK.v2", "PACKAGE", "BUILD", "BUILD.bazel", "TARGETS", ".buckconfig", ".buckrootconfig", "buckal.toml", "target/**", "buck-out/**", ".buckal/**", ".git/**"]
PROFILES = ["dev", "release", "release-lto", "test"]


def root_dir():
    cwd = Path.cwd().resolve()
    for path in [cwd, *cwd.parents]:
        if (path / "flake.lock").exists() and (path / "desktop/aizome/Cargo.toml").exists():
            return path
    raise SystemExit("Run inside the Sekka checkout")


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()[:20]


def starlark(value):
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, dict):
        return "{" + ", ".join(starlark(k) + ": " + starlark(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "[" + ", ".join(starlark(v) for v in value) + "]"
    return json.dumps(value)


def rule(rule_type, **attrs):
    return rule_type + "(\n" + "".join("    " + k + " = " + starlark(v) + ",\n" for k, v in attrs.items()) + ")\n\n"


def cargo_command(tools, vendor, args, root):
    config = (vendor / ".cargo/config.toml").read_text().replace('directory = "cargo-vendor-dir"', "directory = " + json.dumps(str(vendor)))
    # Cargo accepts an absolute configuration file, avoiding a repo-local
    # environment snapshot or mutation of the user's Cargo configuration.
    state = root / ".buckal"
    state.mkdir(exist_ok=True)
    config_path = state / "cargo-config.toml"
    if not config_path.exists() or config_path.read_text() != config:
        config_path.write_text(config)
    env = dict(os.environ, RUSTC=tools["rustc"], RUSTC_BOOTSTRAP="1", CARGO_TARGET_DIR=str(state / "cargo-target"))
    env.pop("RUSTC_WRAPPER", None)
    env.pop("RUSTC_WORKSPACE_WRAPPER", None)
    env.pop("RUSTFLAGS", None)
    env.pop("CARGO_ENCODED_RUSTFLAGS", None)
    command = [tools["cargo"], "--config", str(config_path), *args]
    return json.loads(subprocess.run(command, cwd=root, env=env, check=True, text=True, stdout=subprocess.PIPE).stdout)


def package_records(meta, root):
    records = {}
    for package in meta["packages"]:
        manifest = Path(package["manifest_path"])
        external = package["source"] is not None
        path = str(manifest.parent.resolve()) if external else manifest.parent.relative_to(root).as_posix()
        identity = package["id"] if external else "path:" + path + "#" + package["name"] + "@" + package["version"]
        data = {key: package.get(key) for key in ["name", "version", "description", "authors", "homepage", "repository", "license", "license_file", "readme", "rust_version", "links"]}
        data.update(id=identity, path=path, external=external, features=sorted(package["features"]), has_lib=any(any(k in ["lib", "rlib", "dylib", "proc-macro", "cdylib", "staticlib"] for k in t["kind"]) for t in package["targets"]))
        records[package["id"]] = data
    return records


def lto_modes(graph):
    """Adapted from Cargo 1.99.0's LTO planner; see CARGO-LICENSE-MIT.

    https://github.com/rust-lang/cargo/blob/5f94df4789f005f9a352888e8355ffc645b7ed0e/src/compiler/lto.rs
    """
    units = graph["units"]
    modes = {}
    pending = []
    can_lto = {"bin", "staticlib", "cdylib"}
    dynamic = {"dylib", "cdylib", "proc-macro"}

    def host(unit):
        return bool({"custom-build", "proc-macro"} & set(unit["target"]["kind"]))

    def needs_object(kinds):
        return bool((can_lto | dynamic) & set(kinds))

    def object_mode(kinds):
        return "object" if all(kind == "dylib" for kind in kinds) else "object-bitcode"

    for index in graph["roots"]:
        unit = units[index]
        requested = unit["profile"]["lto"]
        kinds = unit["target"]["crate_types"]
        if requested in (False, "false") or host(unit):
            mode = "object"
        elif requested == "off":
            mode = "off"
        else:
            mode = object_mode(kinds) if needs_object(kinds) else "bitcode"
        pending.append((index, mode))

    while pending:
        index, parent = pending.pop()
        unit = units[index]
        kinds = ["bin"] if unit["mode"] in {"test", "doctest"} else unit["target"]["crate_types"]
        requested = unit["profile"]["lto"]
        if host(unit):
            mode = "object"
        elif all(kind in can_lto for kind in kinds):
            mode = "object" if requested in (False, "false") else "off" if requested == "off" else "run:" + ("fat" if requested is True else requested)
        elif parent.startswith("run:"):
            mode = object_mode(kinds) if needs_object(kinds) else "bitcode"
        elif parent == "bitcode" and needs_object(kinds):
            mode = object_mode(kinds)
        else:
            mode = parent
        previous = modes.get(index)
        if previous is not None and previous != mode:
            if previous.startswith("run:") or mode.startswith("run:"):
                mode = mode if mode.startswith("run:") else previous
            elif "off" in (previous, mode):
                mode = "off"
            else:
                mode = "object-bitcode"
        if previous == mode:
            continue
        modes[index] = mode
        pending.extend((dep["index"], mode) for dep in unit["dependencies"])
    return modes


def units_from_graph(graph, packages, meta):
    raw = graph["units"]
    prepared = []
    metadata = {p["id"]: p for p in meta["packages"]}
    modes = lto_modes(graph)
    for index, unit in enumerate(raw):
        package = packages[unit["pkg_id"]]
        target = dict(unit["target"])
        target["src_path"] = Path(target["src_path"]).relative_to(Path(metadata[unit["pkg_id"]]["manifest_path"]).parent).as_posix()
        prepared.append({"package": package, "target": target, "profile": unit["profile"], "platform": unit["platform"], "mode": unit["mode"], "features": unit["features"], "dependencies": [{k: v for k, v in dep.items() if k != "index"} for dep in unit["dependencies"]]})
        prepared[-1]["lto_mode"] = modes[index]
    abi_targets = {}
    for index, unit in enumerate(prepared):
        if unit["package"]["name"] != "aizome-comp-core" or unit["mode"] != "build" or "dylib" not in unit["target"]["crate_types"]:
            continue
        for dependency in raw[index]["dependencies"]:
            script = prepared[dependency["index"]]
            if script["mode"] == "run-custom-build" and script["package"]["id"] == unit["package"]["id"]:
                script["abi_target"] = {"profile": unit["profile"], "lto_mode": unit["lto_mode"]}
                abi_targets[dependency["index"]] = index
    keys = {}
    visiting = set()
    def key(index):
        if index in keys:
            return keys[index]
        if index in visiting:
            raise ValueError("Cargo unit graph unexpectedly cyclic")
        visiting.add(index)
        spec = prepared[index]
        identity = {k: v for k, v in spec.items() if k not in {"package", "dependencies"}}
        identity["package"] = spec["package"]["id"]
        identity["dependencies"] = sorted([(key(dep["index"]), {k: v for k, v in dep.items() if k != "index"}) for dep in raw[index]["dependencies"]], key=canonical)
        keys[index] = digest(identity)
        visiting.remove(index)
        return keys[index]
    for index, spec in enumerate(prepared):
        spec["key"] = key(index)
        name = spec["target"]["name"].replace("-", "_")
        kinds = spec["target"]["crate_types"]
        if spec["mode"] == "run-custom-build":
            filename = ""
        elif spec["mode"] == "test" or "bin" in kinds:
            filename = name + "-" + spec["key"]
        elif any(kind in kinds for kind in ["dylib", "proc-macro", "cdylib"]):
            filename = "lib" + name + "-" + spec["key"] + ".so"
        elif "staticlib" in kinds:
            filename = "lib" + name + "-" + spec["key"] + ".a"
        else:
            filename = "lib" + name + "-" + spec["key"] + ".rlib"
        spec["filename"] = filename
    # The final crate's metadata includes its build-script dependency. Fill it
    # only after hashing the DAG, rather than introducing an identity cycle.
    for script, target in abi_targets.items():
        prepared[script]["abi_target"]["key"] = keys[target]
    return prepared, keys


def input_fingerprints(root, meta, manifest):
    paths = {manifest, root / "flake.lock", Path(meta["workspace_root"]) / "Cargo.lock"}
    for package in meta["packages"]:
        if package["source"] is not None:
            continue
        path = Path(package["manifest_path"])
        paths.add(path)
        for ancestor in path.parent.parents:
            if not ancestor.is_relative_to(root):
                break
            if (ancestor / "Cargo.toml").exists():
                paths.add(ancestor / "Cargo.toml")
    paths.update(root / "build/buck2" / name for name in ["generate.py", "action.py", "units.bzl", "platforms.bzl"])
    return {path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(paths)}


def outside_data(root, package_path):
    """Use the same literal-include contract as the existing Bazel generator."""
    base = root / package_path
    found = set()
    patterns = [
        (re.compile(r'include_(?:str|bytes)!\s*\(\s*"([^"]+)"'), False, False),
        (re.compile(r'include_(?:str|bytes)!\s*\(\s*concat!\(\s*"([^"]+)"'), False, True),
        (re.compile(r'env!\(\s*"CARGO_MANIFEST_DIR"\s*\)\s*\)?\s*\.join\(\s*(?:format!\(\s*)?"([^"]+)"'), True, False),
    ]
    for source in base.rglob("*.rs"):
        if any(part in {"target", "buck-out", ".git"} for part in source.relative_to(base).parts):
            continue
        text = source.read_text(errors="replace")
        for pattern, from_manifest, prefix in patterns:
            for match in pattern.finditer(text):
                value = match.group(1)
                if prefix:
                    value = value.rsplit("/", 1)[0] if "/" in value else "."
                value = re.sub(r"\{[^}]*\}", "*", value)
                parent = base if from_manifest else source.parent
                candidate = Path(os.path.normpath(parent / value))
                if not candidate.is_relative_to(root):
                    continue
                for path in root.glob(candidate.relative_to(root).as_posix()):
                    if path.is_relative_to(base) or base.is_relative_to(path):
                        continue
                    found.update(p for p in (path.rglob("*") if path.is_dir() else [path]) if p.is_file() and p.name not in EXCLUDED)
    return sorted(p.relative_to(root).as_posix() for p in found)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest-path", default="desktop/aizome/Cargo.toml")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--features", default="", help="Cargo workspace feature selection, including package/feature")
    parser.add_argument("--no-default-features", action="store_true")
    args = parser.parse_args()
    root = root_dir()
    tools = json.loads(Path(os.environ["SEKKA_BUCK2_ENV"]).read_text())
    vendor = Path(os.environ["SEKKA_BUCK2_VENDOR"]).resolve()
    manifest = (root / args.manifest_path).resolve()
    feature_args = (["--features", args.features] if args.features else []) + (["--no-default-features"] if args.no_default_features else [])
    meta = cargo_command(tools, vendor, ["metadata", "--format-version", "1", "--locked", "--offline", "--manifest-path", str(manifest), *feature_args], root)
    packages = package_records(meta, root)
    files = {}
    sources = {}
    first_party = {}
    external_rules = GENERATED + 'load("//build/buck2:units.bzl", "cargo_source")\n\n'
    source_exports = {}
    owners = {p["path"] for p in packages.values() if not p["external"]}
    for path in list(owners):
        for ancestor in (root / path).parents:
            if not ancestor.is_relative_to(root):
                break
            if (ancestor / "Cargo.toml").exists():
                owners.add(ancestor.relative_to(root).as_posix())
    owners = sorted(owners, key=len, reverse=True)
    for pkgid, package in sorted(packages.items()):
        if package["external"]:
            name = "source-" + digest(package["id"])
            external_rules += rule("cargo_source", name=name, store_path=package["path"], visibility=["PUBLIC"])
            sources[pkgid] = "//build/buck2/sources:" + name
        else:
            path = package["path"]
            sources[pkgid] = "//" + path + ":cargo-source"
            additions = {}
            for data_path in outside_data(root, path):
                owner = next((p for p in owners if data_path.startswith(p + "/")), "")
                relative = data_path[len(owner) + 1:] if owner else data_path
                name = "cargo-data-" + digest(relative)
                source_exports.setdefault(owner, {})[name] = relative
                additions[data_path] = "//" + owner + ":" + name
            first_party[path] = GENERATED + 'load("//build/buck2:units.bzl", "cargo_source")\n\n' + 'cargo_source(\n    name = "cargo-source",\n    prefix = ' + starlark(path) + ',\n    files = {' + starlark(path + "/") + ' + p: p for p in glob(["**/*"], exclude = ' + starlark(EXCLUDED) + ')} | ' + starlark(additions) + ',\n    visibility = ["PUBLIC"],\n)\n\n'
    files["build/buck2/sources/BUCK"] = external_rules
    workspace = Path(meta["workspace_root"]).relative_to(root).as_posix()
    workspace_source = "//" + workspace + ":cargo-workspace"
    files[workspace + "/BUCK"] = GENERATED + 'load("//build/buck2:units.bzl", "cargo_source")\n\n' + rule("cargo_source", name="cargo-workspace", files={"Cargo.toml": "Cargo.toml", "Cargo.lock": "Cargo.lock"}, visibility=["PUBLIC"])
    targets = {profile: [] for profile in PROFILES}
    discovery = {profile: [] for profile in PROFILES}
    excluded_lto_packages = set()
    for profile in PROFILES:
        command = ["test" if profile == "test" else "build", "--locked", "--offline", "--manifest-path", str(manifest), "--workspace", "--unit-graph", "-Z", "unstable-options"]
        command += feature_args
        if profile == "test":
            command += ["--lib", "--bins", "--tests"]
        else:
            command += ["--profile", profile]
        if profile == "release-lto":
            for package in meta["packages"]:
                if any("dylib" in t["crate_types"] for t in package["targets"]) or package["name"] == "aizome-comp":
                    command += ["--exclude", package["name"]]
                    excluded_lto_packages.add(package["name"])
        graph = cargo_command(tools, vendor, command, root)
        units, keys = units_from_graph(graph, packages, meta)
        graph_path = "build/buck2/graph/" + profile
        text = GENERATED + 'load("//build/buck2:units.bzl", "cargo_unit")\n\n'
        for index, spec in sorted(enumerate(units), key=lambda item: item[1]["key"]):
            deps = [":" + keys[dep["index"]] for dep in graph["units"][index]["dependencies"]]
            extras = {}
            if spec["mode"] == "run-custom-build" and spec["package"]["name"] == "aizome-comp-core":
                extras[workspace] = workspace_source
                # ABI build.rs discovers path dependencies from Cargo.lock and
                # hashes their exact sources. Keep its input set explicit.
                nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
                pending = [graph["units"][index]["pkg_id"]]
                seen = set()
                while pending:
                    pkgid = pending.pop()
                    if pkgid in seen:
                        continue
                    seen.add(pkgid)
                    pending.extend(nodes[pkgid]["dependencies"])
                for pkgid in sorted(seen):
                    package = packages[pkgid]
                    if not package["external"] and package["id"] != spec["package"]["id"]:
                        extras[package["path"]] = sources[pkgid]
            text += rule("cargo_unit", name=spec["key"], spec=canonical(spec), source=sources[graph["units"][index]["pkg_id"]], deps=deps, extra_sources=extras, visibility=["PUBLIC"])
            discovery[profile].append({"label": "//" + graph_path + ":" + spec["key"], "package": spec["package"]["name"], "package_id": spec["package"]["id"], "target": spec["target"]["name"], "kind": spec["target"]["kind"], "mode": spec["mode"], "filename": spec["filename"], "features": spec["features"], "dependencies": ["//" + graph_path + dep for dep in deps]})
        files[graph_path + "/BUCK"] = text
        for index in sorted(graph["roots"], key=lambda item: units[item]["key"]):
            spec = units[index]
            if spec["package"]["external"]:
                continue
            alias = spec["target"]["name"] + "-" + ("test" if spec["mode"] == "test" else "build") + "-" + profile
            if spec["mode"] == "test":
                alias += "-" + "-".join(spec["target"]["kind"])
            path = spec["package"]["path"]
            first_party[path] += rule("alias", name=alias, actual="//" + graph_path + ":" + spec["key"], visibility=["PUBLIC"])
            targets[profile].append({"label": "//" + path + ":" + alias, "unit_label": "//" + graph_path + ":" + spec["key"], "package": spec["package"]["name"], "target": spec["target"]["name"], "kind": spec["target"]["kind"], "mode": spec["mode"], "filename": spec["filename"]})
    # Rust dylibs cannot participate in LTO. Keep the complete runtime by
    # explicitly depending on the already-generated non-LTO release graph.
    release_units = {unit["label"]: unit for unit in discovery["release"]}
    pending = []
    for target in targets["release"]:
        if target["package"] not in excluded_lto_packages:
            continue
        mixed = dict(target, label=target["label"].removesuffix("-release") + "-release-lto")
        path, alias = mixed["label"][2:].split(":", 1)
        first_party[path] += rule("alias", name=alias, actual=mixed["unit_label"], visibility=["PUBLIC"])
        targets["release-lto"].append(mixed)
        pending.append(mixed["unit_label"])
    seen = set()
    while pending:
        label = pending.pop()
        if label in seen:
            continue
        seen.add(label)
        unit = release_units[label]
        discovery["release-lto"].append(unit)
        pending.extend(unit["dependencies"])
    for profile in PROFILES:
        targets[profile].sort(key=lambda target: target["label"])
        discovery[profile].sort(key=lambda unit: unit["label"])
    for path, text in first_party.items():
        files[path + "/BUCK"] = text
    for owner, exports in source_exports.items():
        path = owner + "/BUCK" if owner else "BUCK"
        files.setdefault(path, GENERATED)
        for name, src in sorted(exports.items()):
            files[path] += rule("export_file", name=name, src=src, visibility=["PUBLIC"])
    files["build/buck2/targets.json"] = json.dumps(targets, indent=2, sort_keys=True) + "\n"
    files["build/buck2/units.json"] = json.dumps(discovery, indent=2, sort_keys=True) + "\n"
    state_path = root / "build/buck2/graph.lock.json"
    previous = json.loads(state_path.read_text()) if state_path.exists() else {}
    state = {"version": 1, "manifest": manifest.relative_to(root).as_posix(), "inputs": input_fingerprints(root, meta, manifest), "vendor": str(vendor), "rustc": tools["rustc"], "cargo": tools["cargo"], "generated": {path: hashlib.sha256(content.encode()).hexdigest() for path, content in files.items()}}
    state["features"] = args.features
    state["no_default_features"] = args.no_default_features
    files["build/buck2/graph.lock.json"] = json.dumps(state, indent=2, sort_keys=True) + "\n"
    stale = []
    for path, content in files.items():
        dest = root / path
        if not dest.exists() or dest.read_text() != content:
            stale.append(path)
            if not args.check:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(content)
    for path in previous.get("generated", {}):
        if path not in files:
            stale.append(path)
            dest = root / path
            if not args.check and dest.exists():
                if not dest.read_text().startswith(GENERATED):
                    raise SystemExit("Refusing to remove non-generated file " + path)
                dest.unlink()
    if args.check and stale:
        raise SystemExit("Cargo/Buck graph is stale; run sekka-buck2-generate:\n" + "\n".join(stale))
    print("Cargo unit graph " + ("checked" if args.check else "generated") + ": " + ", ".join(f"{p}={len(t)} roots" for p, t in targets.items()))


if __name__ == "__main__":
    main()
