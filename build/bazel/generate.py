#!/usr/bin/env python3
"""Write Bazel's view of Aizome's Cargo workspace from `cargo metadata`.

Cargo's manifests and lock stay the source of truth (docs/bazel-build-plan.md);
this writes what Bazel reads from them:

- build/bazel/aizome-cargo/: a mirror of the workspace's resolved packages,
  manifests only, for crate_universe. Aizome's path dependencies leave the
  workspace (Yukimi's and Hotaru's crates) and come back into it
  (yukimi-system on aizome-ipc), which crate_universe can't splice: it
  copies a workspace elsewhere and Cargo then sees two aizome-ipc packages.
  The mirror has one root above them all, the same relative layout, Aizome's
  members' dependencies (and only theirs with dev-dependencies, as Cargo
  resolves them) and its [patch] table, so it resolves to Aizome's own
  Cargo.lock with the same features.
- a BUILD.bazel in each of those packages' directories: its library,
  binaries, build script and tests, with the features and dependencies Cargo
  resolved for x86_64 Linux. crates.io's crates come from crate_universe
  (`@aizome_crates`); files a crate includes or a test reads come from the
  sources (`include_str!`, `include_bytes!`, `env!("CARGO_MANIFEST_DIR")`).
  Nix's package sources leave these files out (desktop/aizome/nix).

Run it in `nix develop .#bazel` after changing a manifest or Cargo.lock, then
repin (build/bazel/repin.py); `--check` fails if anything would change.
"""
import argparse
import hashlib
import json
import os
import re
from pathlib import Path
import subprocess
import sys
import tomllib


ROOT = Path(__file__).resolve().parents[2]
WORKSPACE = ROOT / "desktop/aizome"
MIRROR = ROOT / "build/bazel/aizome-cargo"
FEATURES_FILE = ROOT / "build/bazel/features.json"
FEATURES = json.loads(FEATURES_FILE.read_text())
STATE_FILE = ROOT / "build/bazel/graph-state.json"
GENERATED = "# Generated by build/bazel/generate.py from `cargo metadata`; do not edit.\n"
# The one platform Bazel builds for (build/bazel/platforms).
TARGET_CFG = {
    "target_os": "linux",
    "target_family": "unix",
    "target_arch": "x86_64",
    "target_env": "gnu",
    "target_vendor": "unknown",
    "target_pointer_width": "64",
    "target_endian": "little",
    "unix": True,
}


def metadata(path=None):
    if path:
        return json.loads(Path(path).read_text())
    cargo = os.environ.get("CARGO", "cargo")
    out = subprocess.run(
        [cargo, "metadata", "--format-version", "1", "--locked",
         "--manifest-path", str(WORKSPACE / "Cargo.toml"),
         *(["--features", ",".join(FEATURES)] if FEATURES else [])],
        check=True, stdout=subprocess.PIPE, text=True,
    ).stdout
    return json.loads(out)


# The checkout `cargo metadata` ran in, whose absolute paths it reports.
SOURCE_ROOT = ROOT


def relative(path):
    return Path(os.path.normpath(path)).relative_to(SOURCE_ROOT).as_posix()


def toml_value(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_value(v)}" for k, v in value.items()) + " }"
    raise TypeError(value)


def toml_key(key):
    return key if key.replace("-", "").replace("_", "").isalnum() else json.dumps(key)


def git_spec(source):
    """A dependency's `git+URL?rev=…` source as manifest keys."""
    url, _, query = source.removeprefix("git+").partition("?")
    spec = {"git": url}
    for part in filter(None, query.split("&")):
        key, _, value = part.partition("=")
        spec[key] = value
    return spec


def dependency_spec(dep, package_dir, packages_by_path):
    spec = {}
    if dep.get("rename"):
        spec["package"] = dep["name"]
    if dep.get("path"):
        target = relative(dep["path"])
        if target not in packages_by_path:
            sys.exit(f"{dep['name']}: path dependency {target} is not a resolved package")
        spec["path"] = os.path.relpath(target, package_dir)
    elif dep["source"] and dep["source"].startswith("git+"):
        spec.update(git_spec(dep["source"]))
    if dep["req"] != "*" or not spec:
        spec["version"] = dep["req"]
    if dep["optional"]:
        spec["optional"] = True
    if not dep["uses_default_features"]:
        spec["default-features"] = False
    if dep["features"]:
        spec["features"] = dep["features"]
    return dep.get("rename") or dep["name"], spec


def mirror_manifest(package, member, packages_by_path):
    """A package's manifest in the mirror: what resolution reads, no targets."""
    package_dir = relative(Path(package["manifest_path"]).parent)
    empty = os.path.relpath("empty.rs", package_dir)
    lines = [
        GENERATED,
        "[package]",
        f"name = {toml_value(package['name'])}",
        f"version = {toml_value(package['version'])}",
        f"edition = {toml_value(package['edition'])}",
    ]
    if package.get("links"):
        lines.append(f"links = {toml_value(package['links'])}")
    kinds = {k for t in package["targets"] for k in t["kind"]}
    if "custom-build" in kinds:
        lines.append(f"build = {toml_value(empty)}")
    lines += ["", "[lib]", f"path = {toml_value(empty)}"]
    features = dict(package["features"])
    selected = [f.split("/", 1)[1] for f in FEATURES if f.startswith(package["name"] + "/")]
    if selected:
        features["default"] = sorted(set(features.get("default", []) + selected))
    if features:
        lines += ["", "[features]"]
        lines += [f"{toml_key(k)} = {toml_value(v)}" for k, v in sorted(features.items())]
    sections = {}
    for dep in package["dependencies"]:
        if dep["kind"] == "dev" and not member:
            continue
        table = {None: "dependencies", "build": "build-dependencies", "dev": "dev-dependencies"}[dep["kind"]]
        if dep["target"]:
            table = f"target.{json.dumps(dep['target'])}.{table}"
        key, spec = dependency_spec(dep, package_dir, packages_by_path)
        sections.setdefault(table, []).append(f"{toml_key(key)} = {toml_value(spec)}")
    for table in sorted(sections):
        lines += ["", f"[{table}]"] + sorted(sections[table])
    return package_dir, "\n".join(lines) + "\n"


def mirror_files(meta):
    members = set(meta["workspace_members"])
    path_packages = [p for p in meta["packages"] if p["source"] is None]
    packages_by_path = {relative(Path(p["manifest_path"]).parent): p for p in path_packages}
    files = {}
    for package in path_packages:
        package_dir, text = mirror_manifest(package, package["id"] in members, packages_by_path)
        files[f"{package_dir}/Cargo.toml"] = text
    root = tomllib.loads((WORKSPACE / "Cargo.toml").read_text())
    patches = []
    for registry, table in sorted(root.get("patch", {}).items()):
        patches += ["", f"[patch.{toml_key(registry)}]"]
        for name, spec in sorted(table.items()):
            spec = dict(spec)
            if "path" in spec:
                spec["path"] = os.path.normpath(Path("desktop/aizome") / spec["path"])
            patches.append(f"{toml_key(name)} = {toml_value(spec)}")
    files["Cargo.toml"] = "\n".join([
        GENERATED,
        "# Aizome's packages (desktop/aizome/Cargo.toml and its path dependencies),",
        "# for crate_universe: build/bazel/generate.py.",
        "[workspace]",
        f"resolver = {toml_value(root['workspace'].get('resolver', '3'))}",
        f"members = {toml_value(sorted(packages_by_path))}",
        *patches,
    ]) + "\n"
    files["empty.rs"] = "// Every package's target in the mirror: build/bazel/generate.py.\n"
    files["BUILD.bazel"] = GENERATED + 'exports_files(["Cargo.toml"])\n'
    return {MIRROR / name: text for name, text in files.items()}


# Packages Cargo can't see from a manifest: what their build scripts read
# (labels, or package-relative globs) and the environment they take from the
# native one (build/bazel/native.bzl).
BUILD_SCRIPT_DATA = {
    # The ABI fingerprint (its build.rs) reads the workspace's lock and
    # manifest, finds path packages by their manifests and hashes the
    # sources of the ones in the core's closure.
    "aizome-comp-core": ["//desktop/aizome:Cargo.lock", "//desktop/aizome:Cargo.toml", "@MANIFESTS", "@CLOSURE_SOURCES"],
}
# Tests that need Cargo itself, which Bazel's tests don't run: aizome-comp's
# reload test rebuilds the logic library with `cargo build`. The build
# plan's reload qualification covers Bazel's own matched set instead.
CARGO_TESTS = {"aizome-comp": {"reload"}}
BUILD_SCRIPT_ENV = {
    "aizome-network-agent": {"PATH": "$(BUILD_PATH)", "PKG_CONFIG": "$(PKG_CONFIG)", "PKG_CONFIG_PATH": "$(PKG_CONFIG_PATH)"},
}
# Cargo workspaces whose roots hold files a crate reads from outside its own
# directory: their BUILD.bazel exports them.
WORKSPACE_ROOTS = ["desktop/aizome", "apps/hotaru", "apps/yukimi"]
INCLUDE = re.compile(r'include_(?:str|bytes)!\s*\(\s*"([^"]+)"\s*\)')
INCLUDE_PREFIX = re.compile(r'include_(?:str|bytes)!\s*\(\s*concat!\(\s*"([^"]+)"')
MANIFEST_DIR = re.compile(r'env!\(\s*"CARGO_MANIFEST_DIR"\s*\)\s*\)?\s*(?:,\s*"([^"]*)"|\.join\(\s*"([^"]*)")')


def cfg_matches(expr):
    """Whether a dependency's `target` (a triple or `cfg(…)`) holds here."""
    if expr is None:
        return True
    if not expr.startswith("cfg("):
        return expr == "x86_64-unknown-linux-gnu"
    tokens = re.findall(r'"[^"]*"|[A-Za-z_][A-Za-z0-9_]*|[(),=]', expr)
    pos = 0

    def take():
        nonlocal pos
        pos += 1
        return tokens[pos - 1]

    def pred():
        name = take()
        if name in ("all", "any", "not"):
            assert take() == "("
            values = []
            while tokens[pos] != ")":
                values.append(pred())
                if tokens[pos] == ",":
                    take()
            take()
            return {"all": all(values), "any": any(values), "not": not values[0] if values else True}[name]
        if pos < len(tokens) and tokens[pos] == "=":
            take()
            return TARGET_CFG.get(name) == take().strip('"')
        return TARGET_CFG.get(name) is True

    assert take() == "cfg" and take() == "("
    result = pred()
    assert take() == ")"
    return result


def starlark(value, indent=4):
    pad = " " * indent
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, str):
        return value[1:] if value.startswith("\0") else json.dumps(value)
    if isinstance(value, list):
        if not value:
            return "[]"
        if len(value) == 1 and len(starlark(value[0])) < 60:
            return f"[{starlark(value[0])}]"
        return "[\n" + "".join(f"{pad}    {starlark(v, indent + 4)},\n" for v in value) + f"{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        return "{\n" + "".join(f"{pad}    {json.dumps(k)}: {starlark(v, indent + 4)},\n" for k, v in value.items()) + f"{pad}}}"
    raise TypeError(value)


def files(items):
    """Labels and globs as one list expression."""
    labels = [x for x in dict.fromkeys(items) if not x.startswith("\0")]
    globs = [x[1:] for x in dict.fromkeys(items) if x.startswith("\0")]
    if not globs:
        return labels
    return "\0" + " + ".join(globs + ([starlark(labels, 4)] if labels else []))


def call(rule, **attrs):
    body = "".join(f"    {k} = {starlark(v)},\n" for k, v in attrs.items() if v not in (None, [], {}))
    return f"{rule}(\n{body})\n"


def glob(patterns, exclude=None):
    inner = starlark(patterns, 4)
    if exclude:
        return "\0glob(" + inner + ", exclude = " + starlark(exclude, 4) + ", allow_empty = True)"
    return "\0glob(" + inner + ", allow_empty = True)"


def crate_name(package):
    for target in package["targets"]:
        if set(target["kind"]) & {"lib", "rlib", "dylib", "proc-macro", "cdylib", "staticlib"}:
            return target["name"].replace("-", "_")
    return None


class Workspace:
    def __init__(self, meta):
        self.packages = {p["id"]: p for p in meta["packages"]}
        self.nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        self.members = set(meta["workspace_members"])
        self.path_packages = {i: p for i, p in self.packages.items() if p["source"] is None}
        self.dirs = {i: relative(Path(p["manifest_path"]).parent) for i, p in self.path_packages.items()}
        self.owners = sorted(set(self.dirs.values()) | set(WORKSPACE_ROOTS), key=len, reverse=True)
        # Files each package exports to others, and filegroups of directories.
        self.exports = {d: set() for d in self.owners}
        self.groups = {d: set() for d in self.owners}

    def label(self, package_id):
        package = self.packages[package_id]
        if package["source"] is None:
            return f"//{self.dirs[package_id]}:{crate_name(package)}"
        return f"@aizome_crates//:{package['name']}-{package['version']}"

    def is_proc_macro(self, package_id):
        return any("proc-macro" in t["kind"] for t in self.packages[package_id]["targets"])

    def deps(self, package_id, kinds):
        """Labels of a package's dependencies of these kinds, for Linux."""
        deps, proc_macros, aliases = set(), set(), {}
        for dep in self.nodes[package_id]["deps"]:
            if dep["pkg"] == package_id:
                continue
            if not any(k["kind"] in kinds and cfg_matches(k["target"]) for k in dep["dep_kinds"]):
                continue
            label = self.label(dep["pkg"])
            (proc_macros if self.is_proc_macro(dep["pkg"]) else deps).add(label)
            if dep["name"] != crate_name(self.packages[dep["pkg"]]):
                aliases[label] = dep["name"]
        return sorted(deps), sorted(proc_macros), dict(sorted(aliases.items()))

    def links_rust_dylib(self, package_id):
        """Whether a package's closure has another Rust dylib in it."""
        return any(
            i != package_id and any("dylib" in t["kind"] for t in self.packages[i]["targets"])
            for i in self.path_closure(package_id)
        )

    def path_closure(self, package_id):
        """The path packages a package's whole closure reaches, every kind of
        dependency, through crates.io's crates too (simdutf8, patched to a
        path, is a dependency of those)."""
        seen, todo = set(), [package_id]
        while todo:
            i = todo.pop()
            if i not in seen:
                seen.add(i)
                todo += [d["pkg"] for d in self.nodes[i]["deps"]]
        return sorted(i for i in seen if i in self.path_packages)

    def owner(self, path):
        for d in self.owners:
            if path == d or path.startswith(d + "/"):
                return d
        return None

    def reference(self, package_dir, path, directory=False):
        """A label for a file (or a directory's files) a target in package_dir reads."""
        owner = self.owner(path)
        if owner is None:
            sys.exit(f"{package_dir}: reads {path}, which no generated package holds")
        inside = path[len(owner) + 1:] if path != owner else ""
        if directory:
            if owner == package_dir:
                return glob([f"{inside}/**" if inside else "**"])
            self.groups[owner].add(inside)
            return f"//{owner}:" + group_name(inside)
        if owner == package_dir:
            return inside
        self.exports[owner].add(inside)
        return f"//{owner}:{inside}"


def group_name(directory):
    return "files_" + re.sub(r"[^A-Za-z0-9]+", "_", directory or "all").strip("_")


def source_files(base, patterns):
    files = []
    for pattern in patterns:
        files += [p for p in base.glob(pattern) if p.is_file() and "target" not in p.relative_to(base).parts]
    return sorted(set(files))


def read_data(ws, package_dir, sources):
    """compile_data and test data a target's sources name."""
    compile_data, data = [], []
    base = ROOT / package_dir
    for source in sources:
        text = source.read_text(errors="replace")
        here = source.parent.relative_to(ROOT).as_posix()
        for path in INCLUDE.findall(text):
            target = os.path.normpath(f"{here}/{path}")
            if (ROOT / target).is_file():
                compile_data.append(ws.reference(package_dir, target))
        for prefix in INCLUDE_PREFIX.findall(text):
            directory = os.path.normpath(f"{here}/{prefix.rsplit('/', 1)[0]}" if "/" in prefix else here)
            if (ROOT / directory).is_dir():
                compile_data.append(ws.reference(package_dir, directory, directory=True))
        for joined, appended in MANIFEST_DIR.findall(text):
            rest = (joined or appended).strip("/")
            target = os.path.normpath(f"{package_dir}/{rest}") if rest else package_dir
            if (ROOT / target).is_dir():
                data.append(ws.reference(package_dir, target, directory=True))
            elif (ROOT / target).is_file():
                data.append(ws.reference(package_dir, target))
    def unique(items):
        globbed = [x for x in dict.fromkeys(items) if x.startswith("\0")]
        covered = [re.search(r'"([^"]*)/\*\*"', g) for g in globbed]
        prefixes = [m.group(1) + "/" for m in covered if m]
        labels = sorted(set(x for x in items if not x.startswith("\0")))
        return [x for x in labels if ":" in x or not any(x.startswith(p) for p in prefixes)] + globbed

    return unique(compile_data), unique(data)


def target_sources(package_dir, target):
    """A target's source globs (its root's top directory) and its root."""
    rel = Path(relative(target["src_path"])).relative_to(package_dir)
    top = rel.parts[0] if len(rel.parts) > 1 else None
    return [f"{top}/**/*.rs"] if top else [rel.as_posix()], rel.as_posix()


def package_build(ws, package_id):
    package = ws.packages[package_id]
    node = ws.nodes[package_id]
    package_dir = ws.dirs[package_id]
    member = package_id in ws.members
    base = ROOT / package_dir
    name, version = package["name"], package["version"]
    features = sorted(node["features"])
    lib = crate_name(package)
    targets = package["targets"]
    script = next((t for t in targets if "custom-build" in t["kind"]), None)
    rules = []
    loads = set()
    # rules_rust names CARGO_PKG_NAME after the target; Cargo, the package.
    env = {"CARGO_PKG_NAME": name}
    # A binary over the compositor's core, a Rust dylib with std linked
    # dynamically (-C prefer-dynamic), links std dynamically too, and needs
    # rules_rust to say so for it to find std when it runs.
    dynamic_std = True if ws.links_rust_dylib(package_id) else None

    normal = ws.deps(package_id, {None})
    build = ws.deps(package_id, {"build"})
    dev = ws.deps(package_id, {None, "dev"})
    own = [":build_script"] if script else []

    if script:
        loads.add(("@rules_rust//cargo:defs.bzl", "cargo_build_script"))
        data = [glob(["**"], exclude=["BUILD", "BUILD.bazel", "BUCK", "PACKAGE", "target/**"])]
        for extra in BUILD_SCRIPT_DATA.get(name, []):
            # Every path package's manifest, by which the script finds them;
            # the sources of those in its closure, which it hashes (through
            # Cargo.lock, whose dependency lists name every kind).
            if extra == "@MANIFESTS":
                data += sorted(f"//{d}:Cargo.toml" for d in set(ws.dirs.values()) if d != package_dir)
            elif extra == "@CLOSURE_SOURCES":
                data += sorted(f"//{ws.dirs[i]}:abi_sources" for i in ws.path_closure(package_id) if i != package_id)
            else:
                data.append(extra)
        script_env = BUILD_SCRIPT_ENV.get(name, {})
        script_compile_data, _ = read_data(ws, package_dir, [ROOT / relative(script["src_path"])])
        rules.append(call(
            "cargo_build_script",
            name="build_script",
            srcs=[relative(script["src_path"]).removeprefix(package_dir + "/")],
            crate_root=relative(script["src_path"]).removeprefix(package_dir + "/"),
            compile_data=files(script_compile_data),
            edition=script["edition"],
            pkg_name=name,
            version=version,
            crate_features=features,
            links=package.get("links"),
            deps=build[0],
            proc_macro_deps=build[1],
            aliases=build[2],
            data=files(data),
            build_script_env=script_env,
            toolchains=["//build/bazel:native"] if script_env else [],
        ))

    lib_target = next((t for t in targets if set(t["kind"]) & {"lib", "rlib", "dylib", "proc-macro"}), None)
    # Every link sees the native libraries' directories, as NIX_LDFLAGS gives
    # them to every link in the Nix build: crates such as input-sys name a
    # library (rustc-link-lib) without saying where it is.
    native = ["@nix_native//:link_search"]
    if lib_target:
        patterns, root = target_sources(package_dir, lib_target)
        compile_data, _ = read_data(ws, package_dir, source_files(base, patterns))
        kind = "rust_dylib_library" if "dylib" in lib_target["kind"] else "rust_proc_macro" if "proc-macro" in lib_target["kind"] else "rust_library"
        loads.add(("@rules_rust//rust:defs.bzl", kind))
        rules.append(call(
            kind,
            name=lib,
            crate_name=lib,
            srcs=glob(patterns),
            crate_root=root,
            compile_data=files(compile_data),
            edition=lib_target["edition"],
            version=version,
            crate_features=features,
            rustc_env=env,
            deps=normal[0] + own + (native if kind == "rust_proc_macro" else []),
            link_deps=native if kind != "rust_proc_macro" else None,
            proc_macro_deps=normal[1],
            aliases=normal[2],
        ))
        if lib_target["test"] and member:
            _, test_data = read_data(ws, package_dir, source_files(base, patterns))
            loads.add(("@rules_rust//rust:defs.bzl", "rust_test"))
            rules.append(call(
                "rust_test",
                name="lib_test",
                crate=":" + lib,
                crate_features=features,
                rustc_env=test_env(ws, package_dir, package, env, bins=False),
                env=TEST_RUN_ENV,
                toolchains=["//build/bazel:test_env"],
                data=files(test_data),
                deps=[d for d in dev[0] if d not in normal[0]],
                proc_macro_deps=[d for d in dev[1] if d not in normal[1]],
                aliases={k: v for k, v in dev[2].items() if k not in normal[2]},
            ))

    for target in targets:
        if "bin" not in target["kind"] or not enabled(target, features):
            continue
        patterns, root = target_sources(package_dir, target)
        compile_data, _ = read_data(ws, package_dir, source_files(base, patterns))
        loads.add(("//build/bazel:runtime.bzl", "sekka_rust_binary"))
        rules.append(call(
            "sekka_rust_binary",
            name=target["name"],
            logic="//desktop/aizome/crates/aizome-comp-logic:aizome_comp_logic" if name == "aizome-comp" else None,
            runtime_bins=["//desktop/aizome/crates/aizome-shell:aizome-shell"] if name == "aizome-comp" else None,
            crate_name=target["name"].replace("-", "_"),
            srcs=glob(patterns),
            crate_root=root,
            compile_data=files(compile_data),
            edition=target["edition"],
            version=version,
            crate_features=features,
            rustc_env=env,
            link_std_dylib=dynamic_std,
            deps=normal[0] + own + ([":" + lib] if lib_target else []),
            link_deps=native,
            proc_macro_deps=normal[1],
            aliases=normal[2],
        ))

    for target in targets:
        if "test" not in target["kind"] or not member or not enabled(target, features):
            continue
        if target["name"] in CARGO_TESTS.get(name, ()):
            continue
        rel = Path(relative(target["src_path"])).relative_to(package_dir).as_posix()
        top = rel.split("/")[0]
        patterns = [f"{top}/**/*.rs"]
        compile_data, test_data = read_data(ws, package_dir, source_files(base, [rel] + patterns))
        loads.add(("@rules_rust//rust:defs.bzl", "rust_test"))
        rules.append(call(
            "rust_test",
            name=test_name(target, targets),
            crate_name=target["name"].replace("-", "_"),
            srcs=glob(patterns),
            crate_root=rel,
            compile_data=files(compile_data),
            edition=target["edition"],
            version=version,
            crate_features=features,
            rustc_env=test_env(ws, package_dir, package, env),
            env=TEST_RUN_ENV,
            toolchains=["//build/bazel:test_env"],
            data=files(test_data + bin_data(package)),
            link_std_dylib=dynamic_std,
            deps=dev[0] + own + ([":" + lib] if lib_target else []),
            link_deps=native,
            proc_macro_deps=dev[1],
            aliases=dev[2],
        ))

    header = [GENERATED]
    by_file = {}
    for file, symbol in sorted(loads):
        by_file.setdefault(file, []).append(symbol)
    header += [f"load({json.dumps(f)}, {', '.join(json.dumps(x) for x in xs)})" for f, xs in sorted(by_file.items())]
    header += ["", 'package(default_visibility = ["//visibility:public"])', ""]
    return package_dir, header, rules


def enabled(target, features):
    return all(f in features for f in target.get("required_features") or [])


def test_name(target, targets):
    names = {t["name"] for t in targets if "test" not in t["kind"]}
    return target["name"] + "_test" if target["name"] in names else target["name"]


# The run-time environment of the package's tests (build/bazel/native.bzl's
# test_env, nix/bazel/toolchains.nix's testEnv).
TEST_RUN_ENV = {name: f"$(TEST_{name})" for name in
                ["AIZOME_FONT_DIR", "FONTCONFIG_FILE", "HOTARU_FONT_DIR", "LD_LIBRARY_PATH", "PATH", "TZDIR"]}


def test_env(ws, package_dir, package, env, bins=True):
    """What Cargo gives a test at compile time, for a test run by Bazel.

    Bazel runs tests in their runfiles' main repository, where the package's
    files sit at their workspace paths, and in a sandbox's private /tmp.
    """
    out = dict(env)
    out["CARGO_MANIFEST_DIR"] = package_dir
    out["CARGO_TARGET_TMPDIR"] = "/tmp"
    for target in package["targets"] if bins else []:
        if "bin" in target["kind"]:
            out[f"CARGO_BIN_EXE_{target['name']}"] = f"$(rootpath :{target['name']})"
    return out


def bin_data(package):
    return [":" + t["name"] for t in package["targets"] if "bin" in t["kind"]]


def build_files(meta):
    ws = Workspace(meta)
    built = {}
    for package_id in sorted(ws.path_packages, key=lambda i: ws.dirs[i]):
        package_dir, header, rules = package_build(ws, package_id)
        built[package_dir] = (header, rules)
    files = {}
    for package_dir in sorted(set(built) | set(WORKSPACE_ROOTS)):
        header, rules = built.get(package_dir, ([GENERATED, 'package(default_visibility = ["//visibility:public"])', ""], []))
        extra = ['exports_files(["Cargo.toml"])' if package_dir not in WORKSPACE_ROOTS or package_dir == "desktop/aizome" else None]
        if package_dir == "desktop/aizome":
            extra = ['exports_files(["Cargo.toml", "Cargo.lock"])']
            targets = []
            for package_id, package in ws.path_packages.items():
                prefix = "//" + ws.dirs[package_id] + ":"
                lib = crate_name(package)
                if lib:
                    targets.append(prefix + lib)
                targets.extend(prefix + t["name"] for t in package["targets"]
                               if "bin" in t["kind"] and enabled(t, ws.nodes[package_id]["features"]))
            extra.append(call("filegroup", name="workspace", srcs=sorted(set(targets))).rstrip())
        exports = sorted(ws.exports.get(package_dir, ()))
        if exports:
            extra.append("exports_files(" + starlark(exports, 0) + ")")
        for directory in sorted(ws.groups.get(package_dir, ())):
            extra.append(call("filegroup", name=group_name(directory),
                              srcs=glob([f"{directory}/**" if directory else "**"], exclude=["BUILD", "BUILD.bazel", "BUCK", "PACKAGE"])).rstrip())
        if package_dir in built:
            extra.append(call("filegroup", name="abi_sources",
                              srcs=glob(["src/**", "build.rs", "Cargo.toml"])).rstrip())
        body = "\n".join(header) + "\n" + "\n\n".join(x for x in extra if x) + "\n"
        if rules:
            body += "\n" + "\n".join(rules)
        files[ROOT / package_dir / "BUILD.bazel"] = body
    return files


def owned(directory):
    """Files a previous run wrote under the mirror."""
    if not directory.exists():
        return set()
    return {p for p in directory.rglob("*") if p.is_file()}


def graph_inputs(package_dirs):
    """Fingerprint declarations, not ordinary Rust code edits.

    Every source filename and include reference is checked, including whether
    its referent exists. Cargo manifests are always hashed in full. Builds can
    therefore check the generated graph without a Cargo registry or index.
    """
    manifests = {ROOT / "desktop/aizome/Cargo.toml"}
    sources = {}
    for directory in package_dirs:
        base = ROOT / directory
        for parent in [base, *base.parents]:
            if parent == ROOT:
                break
            manifest = parent / "Cargo.toml"
            if manifest.is_file():
                manifests.add(manifest)
        for current, directories, names in os.walk(base):
            directories[:] = sorted(d for d in directories if d not in {
                "target", "buck-out", ".buckal", ".git", ".work",
            } and not d.startswith("bazel-"))
            for name in sorted(names):
                if not name.endswith(".rs"):
                    continue
                source = Path(current) / name
                text = source.read_text(errors="replace")
                references = []
                for path in INCLUDE.findall(text):
                    target = source.parent / path
                    references.append(("include", path, target.is_file()))
                for prefix in INCLUDE_PREFIX.findall(text):
                    target = source.parent / prefix.rsplit("/", 1)[0] if "/" in prefix else source.parent
                    references.append(("prefix", prefix, target.is_dir()))
                for joined, appended in MANIFEST_DIR.findall(text):
                    rest = (joined or appended).strip("/")
                    target = base / rest
                    references.append(("manifest", rest, target.is_file(), target.is_dir()))
                sources[source.relative_to(ROOT).as_posix()] = references
    inputs = {}
    for path in sorted(manifests | {
        ROOT / "desktop/aizome/Cargo.lock", ROOT / "MODULE.bazel",
        FEATURES_FILE, ROOT / "build/bazel/generate.py",
    }):
        inputs[path.relative_to(ROOT).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    inputs["rust_graph"] = hashlib.sha256(json.dumps(sources, sort_keys=True).encode()).hexdigest()
    return inputs


def check_fast():
    if not STATE_FILE.is_file():
        print("missing Bazel graph snapshot: run scripts/sekka-bazel generate", file=sys.stderr)
        return 1
    state = json.loads(STATE_FILE.read_text())
    changed = graph_inputs(state["package_dirs"]) != state["inputs"]
    for name, digest in state["outputs"].items():
        path = ROOT / name
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            print(f"out of date: {name}", file=sys.stderr)
            changed = True
    if changed:
        print("Cargo manifests, source graph, or generated declarations changed; run scripts/sekka-bazel generate", file=sys.stderr)
    return int(changed)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any file would change")
    parser.add_argument("--check-fast", action="store_true", help="check Cargo/source declarations offline without resolving metadata")
    parser.add_argument("--metadata", help="read `cargo metadata` output from this file")
    parser.add_argument("--features", help="persist comma-separated package/feature selections; empty resets defaults")
    args = parser.parse_args()
    if args.check_fast:
        if args.features is not None:
            parser.error("--features cannot be combined with --check-fast")
        return check_fast()
    global FEATURES
    if args.features is not None:
        if args.check:
            parser.error("--features changes the graph; use it without --check")
        FEATURES = sorted(set(filter(None, args.features.split(","))))
        if any("/" not in f for f in FEATURES):
            parser.error("features must be qualified as package/feature")
    meta = metadata(args.metadata)
    global SOURCE_ROOT
    SOURCE_ROOT = Path(meta["workspace_root"]).parents[1]
    files = mirror_files(meta)
    files.update(build_files(meta))
    files[FEATURES_FILE] = json.dumps(FEATURES, indent=2) + "\n"
    stale = owned(MIRROR) - set(files)
    # Remove BUILD files for path packages Cargo no longer resolves, but
    # never touch hand-written BUILD files or another generator's outputs.
    for manifest in MIRROR.rglob("Cargo.toml"):
        if manifest.parent == MIRROR:
            continue
        old_build = ROOT / manifest.parent.relative_to(MIRROR) / "BUILD.bazel"
        if old_build not in files and old_build.is_file() and old_build.read_text().startswith(GENERATED):
            stale.add(old_build)
    changed = [p for p, text in files.items() if not p.is_file() or p.read_text() != text]
    if args.check:
        for p in sorted(changed) + sorted(stale):
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if changed or stale else check_fast()
    for p in stale:
        p.unlink()
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p])
    package_dirs = sorted(relative(Path(p["manifest_path"]).parent)
                          for p in meta["packages"] if p["source"] is None)
    state = {
        "package_dirs": package_dirs,
        "inputs": graph_inputs(package_dirs),
        "outputs": {p.relative_to(ROOT).as_posix(): hashlib.sha256(text.encode()).hexdigest()
                    for p, text in sorted(files.items())},
    }
    state_text = json.dumps(state, indent=2, sort_keys=True) + "\n"
    if not STATE_FILE.is_file() or STATE_FILE.read_text() != state_text:
        STATE_FILE.write_text(state_text)
    print(f"{len(changed)} written, {len(stale)} removed, {len(files) - len(changed)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
